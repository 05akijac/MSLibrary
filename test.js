'use strict';
const assert=require('node:assert/strict');
const Q=require('./quad-math.js');
const tip=Q.apex();
assert.ok(Math.abs(tip.q-0.705996)<2e-5,`tip q=${tip.q}`);
assert.ok(Math.abs(tip.a-0.236994)<2e-5,`tip a=${tip.a}`);
assert.ok(Math.abs(tip.slope-0.335687)<2e-5);
const p=Q.physicalFromAQ(200,1,4,.22,.68);
const inv=Q.aqFromPhysical(200,1,4,p.U,p.V);
assert.ok(Math.abs(inv.a-.22)<1e-10);
assert.ok(Math.abs(inv.q-.68)<1e-10);
const b=Q.solveWidth(200,1);
assert.ok(Math.abs(b.width-1)<.003,JSON.stringify(b));
assert.ok(b.qLow<b.q && b.q<b.qHigh);
assert.equal(Q.isFirstStable(.20,.70),true);
assert.equal(Q.isFirstStable(.30,.70),false);
const params={targetMz:200,testMz:200,frequencyMHz:1,radiusMm:4,lengthMm:80,axialEVPerCharge:5,a:b.a,q:b.q,x0Mm:.12,y0Mm:.12};
const traj=Q.trajectory(params);
assert.ok(traj.cycles>5 && traj.samples.length>2);
const lost=Q.trajectory({...params,testMz:100});
assert.ok(lost.transmitted===false,JSON.stringify(lost));
console.log('PASS: apex, voltage conversion, 1 Da ideal band, RK4 trajectories', {tip, nominal:b, transmitted:traj.transmitted, lowMassLost:!lost.transmitted});
